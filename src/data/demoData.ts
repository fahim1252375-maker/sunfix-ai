export function generateSimulatedDayCurve(
  capacityKw: number,
  scenario: SimulatedFaultScenario,
): TelemetryPoint[] {
  const hours = [6, 8, 10, 12, 14, 16, 18];
  const isNormal = scenario.id === 'scenario-normal' || !scenario.faultCode;
  return hours.map((h) => {
    const faultActive = !isNormal && h >= 10;
    const sim = computeSimulatedTwinTelemetry({
      capacityKw,
      hourDecimal: h,
      inverterFault: faultActive && scenario.componentId === 'inverter',
      gridFault: faultActive && scenario.componentId === 'grid_meter',
      stringFault: faultActive && scenario.componentId === 'solar_panel',
      batteryFault: faultActive && scenario.componentId === 'battery',
    });
    return {
      hour: formatHourLabel(h),
      expectedKw: sim.expectedKw,
      observedKw: sim.observedKw,
      label: faultActive ? `${scenario.faultCode} [SIM]` : h === 12 ? 'Solar noon [SIM]' : 'Nominal [SIM]',
    };
  });
}

